#!/usr/bin/env node
/**
 * Stop hook: decline, once per session, to end a session that changed user
 * interface files and never ran `a11y-loop audit` after the last change.
 *
 * The skill's §2 says the audit loop is mandatory after any UI change. The
 * skill cannot make it happen. This hook can: when Claude is about to finish,
 * it reads the session transcript, and if UI files were written after the last
 * audit (or with no audit at all), it returns `decision: "block"` with a reason
 * naming the files and the exact commands to run. Claude Code then continues
 * the turn instead of stopping.
 *
 * The gate checks that an audit was run. It cannot check that the audit was
 * clean or covered the right states — the report and a human are for that.
 *
 * Inputs (stdin, JSON, per code.claude.com/docs/en/hooks#stop):
 *   session_id        keys the once-per-session state
 *   transcript_path   the session JSONL; read, never written
 *   cwd               only used to shorten file paths in the reason
 *   stop_hook_active  true when Claude Code is already continuing because a
 *                     stop hook blocked; this gate then never blocks
 *
 * Outputs (stdout):
 *   `{"decision":"block","reason":"…"}` and exit 0, or nothing and exit 0.
 *   There is no other output. It never returns `approve` or any other
 *   decision, and it never exits 2.
 *
 * Four properties matter more than catching everything:
 *
 *   1. **It never breaks a session.** Empty stdin, bad JSON, a missing or
 *      unreadable transcript, an unreadable state file, a missing lib, a bug in
 *      here — every failure path emits nothing and exits 0, which lets Claude
 *      stop as it would have without the plugin.
 *   2. **It blocks at most once per session.** The first block records the
 *      session id in `${CLAUDE_PLUGIN_DATA}/a11y-loop-audit-gate.json`; every
 *      later Stop in that session passes silently, whatever the transcript
 *      says. If the state cannot be written, it does not block at all, because
 *      a block it cannot remember is a block it could repeat.
 *   3. **It never blocks a continuation.** When `stop_hook_active` is true it
 *      passes, so it cannot be one of the hooks that keeps Claude in a loop
 *      (Claude Code also caps consecutive stop-hook continuations at eight).
 *   4. **It can be turned off.** `A11Y_LOOP_AUDIT_GATE=off` (or `0`, `false`,
 *      `disabled`) silences it.
 *
 * The decision — which tool calls are UI edits, which are audits, and whether
 * an audit followed the last edit — lives in `src/lib/audit-gate.js`. The
 * plugin ships only its own folder, so this hook loads a byte-for-byte copy
 * from `./lib/audit-gate.mjs`, regenerated by `npm run sync-plugin` and
 * checked by `test/unit/plugin-sync.test.js`.
 *
 * Known limits, on purpose: a file written by a shell command (a heredoc, a
 * build step) is not seen as a UI edit, and edits made inside a subagent live
 * in the subagent's own transcript. Claude Code also writes the transcript
 * asynchronously, so a tool call made in the last moment before Stop can be
 * missing; the once-per-session cap bounds what that can cost.
 */

import { readFileSync, writeFileSync, mkdirSync, realpathSync } from 'node:fs';
import { homedir, tmpdir } from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

/**
 * The shared decision, loaded dynamically so that a missing or broken
 * `./lib/audit-gate.mjs` leaves the hook loadable and lets `main()` take its
 * own silent exit-0 path. A static import would fail at module load, and Node
 * would exit 1 before any of this file's failure handling ran.
 */
let lib = null;
let libError = null;
try {
  lib = await import('./lib/audit-gate.mjs');
} catch (error) {
  libError = error;
}

const needLib = () => {
  if (!lib) throw libError ?? new Error('hooks/lib/audit-gate.mjs did not load');
  return lib;
};
export const evaluate = (input) => needLib().evaluate(input);

/** Sessions older than this are pruned on the next write. */
const STATE_TTL_MS = 7 * 24 * 60 * 60 * 1000;

/** Hard cap on retained sessions, so the file cannot grow without bound. */
const MAX_STATE_ENTRIES = 500;

/** Transcripts larger than this are not read; the gate passes instead of stalling Stop. */
const MAX_TRANSCRIPT_BYTES = 64 * 1024 * 1024;

const STATE_VERSION = 1;
const STATE_FILENAME = 'a11y-loop-audit-gate.json';

/**
 * `${CLAUDE_PLUGIN_DATA}` when Claude Code provides it, the temp directory when
 * it does not. Never relative to the working directory.
 *
 * @returns {string}
 */
export function stateFilePath() {
  const dir = process.env.CLAUDE_PLUGIN_DATA?.trim() || tmpdir();
  return path.join(dir, STATE_FILENAME);
}

function loadState(file) {
  try {
    const parsed = JSON.parse(readFileSync(file, 'utf8'));
    if (parsed?.version === STATE_VERSION && parsed.sessions && typeof parsed.sessions === 'object') {
      return { version: STATE_VERSION, sessions: parsed.sessions };
    }
  } catch {
    // Missing or unreadable: start empty.
  }
  return { version: STATE_VERSION, sessions: {} };
}

/** @returns {boolean} whether the state was written */
function saveState(file, state, now) {
  const fresh = Object.entries(state.sessions).filter(([, t]) => Number.isFinite(t) && now - t < STATE_TTL_MS);
  fresh.sort((a, b) => b[1] - a[1]);
  state.sessions = Object.fromEntries(fresh.slice(0, MAX_STATE_ENTRIES));
  try {
    mkdirSync(path.dirname(file), { recursive: true });
    writeFileSync(file, JSON.stringify(state), 'utf8');
    return true;
  } catch {
    return false;
  }
}

/**
 * @param {NodeJS.ReadStream} stream
 * @returns {Promise<string>}
 */
function readStdin(stream) {
  return new Promise((resolve) => {
    if (stream.isTTY) {
      resolve('');
      return;
    }
    let data = '';
    stream.setEncoding('utf8');
    stream.on('data', (chunk) => {
      data += chunk;
    });
    stream.on('end', () => resolve(data));
    stream.on('error', () => resolve(''));
  });
}

/** The docs' own example shows `transcript_path` starting with `~/`. */
function expandHome(p) {
  return p === '~' || p.startsWith('~/') || p.startsWith('~\\') ? path.join(homedir(), p.slice(1)) : p;
}

/** @returns {string|null} the transcript text, or null when it cannot be read */
function readTranscript(transcriptPath) {
  if (typeof transcriptPath !== 'string' || !transcriptPath.trim()) return null;
  try {
    const buf = readFileSync(expandHome(transcriptPath.trim()));
    if (buf.length > MAX_TRANSCRIPT_BYTES) return null;
    return buf.toString('utf8');
  } catch {
    return null;
  }
}

function killSwitchOn() {
  const v = (process.env.A11Y_LOOP_AUDIT_GATE ?? '').trim().toLowerCase();
  return v === 'off' || v === '0' || v === 'false' || v === 'disabled';
}

/** Emit nothing and exit 0: no decision, so Claude stops as it otherwise would. */
function silent() {
  process.exitCode = 0;
}

export async function main() {
  try {
    if (killSwitchOn()) return silent();
    if (!lib) {
      process.stderr.write(
        `a11y-loop audit gate: skipped, hooks/lib/audit-gate.mjs did not load (${libError?.code ?? libError?.message ?? 'unknown'})\n`,
      );
      return silent();
    }

    const raw = await readStdin(process.stdin);
    if (!raw.trim()) return silent();

    let input;
    try {
      input = JSON.parse(raw);
    } catch {
      return silent();
    }
    if (!input || typeof input !== 'object') return silent();

    const transcriptText = readTranscript(input.transcript_path);
    if (transcriptText === null) return silent();

    const sessionId = typeof input.session_id === 'string' && input.session_id ? input.session_id : null;
    if (!sessionId) return silent(); // no key to remember a block by, so no block

    const file = stateFilePath();
    const state = loadState(file);

    const verdict = evaluate({
      transcriptText,
      stopHookActive: input.stop_hook_active === true,
      alreadyBlocked: Object.hasOwn(state.sessions, sessionId),
      cwd: typeof input.cwd === 'string' ? input.cwd : undefined,
    });
    if (verdict.decision !== 'block') return silent();

    const now = Date.now();
    state.sessions[sessionId] = now;
    if (!saveState(file, state, now)) return silent();

    process.stdout.write(`${JSON.stringify({ decision: 'block', reason: verdict.reason })}\n`);
    process.exitCode = 0;
  } catch {
    // Whatever it was, it is not worth keeping a session open over.
    return silent();
  }
}

/**
 * Whether this module is the process entry point. Node resolves
 * `import.meta.url` through symlinks and junctions but leaves `process.argv[1]`
 * as typed, so a plain comparison is false when the hook is reached through a
 * link and the gate would silently never run. Resolve argv[1] first; if it
 * cannot be resolved, compare it as given. Never throws.
 *
 * @param {string} moduleUrl
 * @param {string|undefined} argv1
 * @returns {boolean}
 */
export function isEntryPoint(moduleUrl, argv1) {
  if (!argv1) return false;
  try {
    let entry = argv1;
    try {
      entry = realpathSync(argv1);
    } catch {
      // Not resolvable: compare the path as given.
    }
    return moduleUrl === pathToFileURL(entry).href;
  } catch {
    return false;
  }
}

if (isEntryPoint(import.meta.url, process.argv[1])) await main();
